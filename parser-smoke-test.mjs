import fs from 'fs';
const html = fs.readFileSync('index.html','utf8');
const body = html.slice(html.indexOf('const RE = {'));
// pull parser+analyze
const parserSrc = body.slice(0, body.indexOf('/* ═══════════════════════════════════════════════════════════════\n   3. RENDER'));
// pull SAMPLE literal
const sStart = body.indexOf('const SAMPLE = `');
const sEnd = body.indexOf('`;', sStart);
const sampleSrc = body.slice(sStart, sEnd+2);
const mod = parserSrc + '\n' + sampleSrc + '\nexport {parseFight, analyze, SAMPLE};';
fs.writeFileSync('_mod.mjs', mod);
const {parseFight, analyze, SAMPLE} = await import('./_mod.mjs');
const f = parseFight(SAMPLE);
const A = analyze(f);
const P=A.P, M=A.M;
console.log('player/monster      :', P, '/', M);
console.log('maxHp               :', f.maxHp[P], f.maxHp[M]);
console.log('startDistance       :', f.startDistance, '| firstMover:', f.firstMover);
console.log('turns logged        :', A.turnsSeen.join(','));
console.log('totalTurns          :', A.totalTurns);
console.log('firstAttackTurn     :', A.firstAttackTurn, '| closedAt:', A.closedAt, '| approachTurns:', A.approachTurns);
console.log('events              :', A.events);
console.log('--- player ---');
console.log(' attacks/hits/miss  :', A.s[P].attacks, A.s[P].hits, A.s[P].misses, '| hitRate', A.hitRateP);
console.log(' rawRolled/dealt    :', A.s[P].rawRolled, A.s[P].dealt);
console.log(' foe AC absorbed    :', A.s[P].acAbsorbedByFoe, '| foe resist absorbed:', A.s[P].resistAbsorbedByFoe);
console.log(' byType             :', A.s[P].byType);
console.log(' nearMisses         :', A.s[P].nearMisses);
console.log('--- monster ---');
console.log(' attacks/hits       :', A.s[M].attacks, A.s[M].hits, '| hitRate', A.hitRateM);
console.log(' rawRolled/dealt    :', A.s[M].rawRolled, A.s[M].dealt);
console.log('--- derived ---');
console.log('mitP (player def)   :', A.mitP);
console.log('mitM (monster def)  :', A.mitM);
console.log('finalP/finalM       :', A.finalP, A.finalM, '| overkill', A.overkill);
console.log('idle player         :', A.idle[P]);
console.log('idle monster        :', A.idle[M]);
console.log('series P            :', A.series[P].map(d=>d.turn+':'+d.hp).join(' '));
console.log('series M            :', A.series[M].map(d=>d.turn+':'+d.hp).join(' '));
console.log('player dmg types    :', f.entities[P]._damages);
console.log('player AC/EV/spd    :', f.entities[P].Ac, f.entities[P].Ev, f.entities[P]['Attack Speed'], '| kind', f.entities[P]._kind);
console.log('monster AC/EV/Rpois :', f.entities[M].Ac, f.entities[M].Ev, f.entities[M].Rpois, '| kind', f.entities[M]._kind);
console.log('outcome             :', f.outcome);
